bit_sizes = [8, 6, 35]
colors = ['lightblue', 'lightgreen', 'lightyellow']

# Pie chart of bit allocation
ax1.pie(bit_sizes, labels=bit_sections, colors=colors, autopct='%1.1f%%')
ax1.set_title('AMBE+2 Frame Bit Allocation (49 bits total)')

# Show null vs voice frame parameters
parameters = ['Pitch', 'Gain', 'Spectral Energy', 'Entropy']
null_values = [0, 0.1, 0.2, 0.1]
voice_values = [1.0, 0.8, 0.9, 0.95]

x = np.arange(len(parameters))
width = 0.35

bars1 = ax2.bar(x - width/2, null_values, width, label='Null Frame', color='gray')
bars2 = ax2.bar(x + width/2, voice_values, width, label='Voice Frame', color='orange')

ax2.set_xlabel('Parameters')
ax2.set_ylabel('Normalized Value')
ax2.set_title('Null Frame vs Voice Frame Parameters')
ax2.set_xticks(x)
ax2.set_xticklabels(parameters)
ax2.legend()
ax2.grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('ambe_null_frame_structure.png', dpi=150)
